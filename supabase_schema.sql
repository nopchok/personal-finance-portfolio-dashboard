-- 4. Itemized Income Items
CREATE TABLE IF NOT EXISTS income_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    income_type TEXT NOT NULL DEFAULT 'ประจำ (Active / Fixed)',
    estimated_amount NUMERIC NOT NULL DEFAULT 0,
    notes TEXT DEFAULT '',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Itemized Expense Items
CREATE TABLE IF NOT EXISTS expense_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    expense_type TEXT NOT NULL DEFAULT 'คงที่ (Fixed)',
    estimated_amount NUMERIC NOT NULL DEFAULT 0,
    notes TEXT DEFAULT '',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Custom Categories
CREATE TABLE IF NOT EXISTS custom_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cat_type TEXT NOT NULL,
    name TEXT NOT NULL,
    UNIQUE(cat_type, name)
);

-- 7. Monthly Snapshots (Historic tracking)
CREATE TABLE IF NOT EXISTS monthly_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_month TEXT UNIQUE NOT NULL,
    income NUMERIC NOT NULL DEFAULT 0,
    expenses NUMERIC NOT NULL DEFAULT 0,
    savings_invested NUMERIC NOT NULL DEFAULT 0,
    total_assets NUMERIC NOT NULL DEFAULT 0,
    total_debts NUMERIC NOT NULL DEFAULT 0,
    net_worth NUMERIC NOT NULL DEFAULT 0,
    notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS) or Allow Public Access (For personal app)
ALTER TABLE assets ENABLE ROW LEVEL SECURITY;
ALTER TABLE liabilities ENABLE ROW LEVEL SECURITY;
ALTER TABLE monthly_profile ENABLE ROW LEVEL SECURITY;
ALTER TABLE income_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE expense_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE custom_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE monthly_snapshots ENABLE ROW LEVEL SECURITY;

-- Create Open Policies for Anon key (Personal Dashboard)
CREATE POLICY "Allow anon read all on assets" ON assets FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow anon read all on liabilities" ON liabilities FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow anon read all on monthly_profile" ON monthly_profile FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow anon read all on income_items" ON income_items FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow anon read all on expense_items" ON expense_items FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow anon read all on custom_categories" ON custom_categories FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow anon read all on monthly_snapshots" ON monthly_snapshots FOR ALL USING (true) WITH CHECK (true);
