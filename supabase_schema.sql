-- =========================================================================
-- Supabase SQL Schema for Minimal Personal Finance & Portfolio Dashboard
-- Run this in Supabase -> SQL Editor -> New Query -> Run
-- =========================================================================

-- 1. Assets table (Investment Portfolio & Fixed Assets)
CREATE TABLE IF NOT EXISTS assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    current_value NUMERIC NOT NULL DEFAULT 0,
    cost_basis NUMERIC NOT NULL DEFAULT 0,
    target_allocation NUMERIC NOT NULL DEFAULT 0,
    monthly_dca NUMERIC NOT NULL DEFAULT 0,
    expected_roi NUMERIC NOT NULL DEFAULT 6.0,
    platform_or_broker TEXT DEFAULT '',
    notes TEXT DEFAULT '',
    asset_type TEXT NOT NULL DEFAULT 'investment',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Liabilities table (Debts / Loans)
CREATE TABLE IF NOT EXISTS liabilities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    total_balance NUMERIC NOT NULL DEFAULT 0,
    monthly_payment NUMERIC NOT NULL DEFAULT 0,
    interest_rate NUMERIC NOT NULL DEFAULT 0,
    notes TEXT DEFAULT '',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Monthly Financial Profile (Active Estimate)
CREATE TABLE IF NOT EXISTS monthly_profile (
    id BIGINT PRIMARY KEY DEFAULT 1,
    salary NUMERIC NOT NULL DEFAULT 50000,
    bonus_or_other_income NUMERIC NOT NULL DEFAULT 0,
    passive_income NUMERIC NOT NULL DEFAULT 0,
    fixed_expenses NUMERIC NOT NULL DEFAULT 15000,
    variable_expense_estimate NUMERIC NOT NULL DEFAULT 15000,
    emergency_fund_target_months INTEGER NOT NULL DEFAULT 6,
    fire_target_monthly_spend NUMERIC NOT NULL DEFAULT 35000,
    fire_expected_return NUMERIC NOT NULL DEFAULT 7.0,
    fire_inflation_rate NUMERIC NOT NULL DEFAULT 2.5,
    fire_current_age INTEGER NOT NULL DEFAULT 30,
    fire_target_age INTEGER NOT NULL DEFAULT 50,
    fire_monthly_dca NUMERIC NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

